"""Prepare generated Flutter Android project for Google Play distribution.

The Android platform is generated by GitHub Actions, not kept in source.
This script pins the Google Play package identity, API 36, app label,
and secure file-backup behavior before building.
"""
from pathlib import Path
import re

app = Path("android/app/build.gradle.kts")
s = app.read_text(encoding="utf8")
if 'applicationId = "com.arosoft.crown_password_studio"' not in s:
    raise SystemExit("Unexpected Flutter applicationId template; refusing to patch.")
s = s.replace('applicationId = "com.arosoft.crown_password_studio"',
              'applicationId = "com.arosoft.crownpasswordstudio"')
s, compile_count = re.subn(r'compileSdk\s*=\s*flutter\.compileSdkVersion',
                           'compileSdk = 36', s, count=1)
s, target_count = re.subn(r'targetSdk\s*=\s*flutter\.targetSdkVersion',
                          'targetSdk = 36', s, count=1)
if compile_count != 1 or target_count != 1:
    raise SystemExit("Generated Gradle SDK template changed; refusing to patch.")
app.write_text(s, encoding="utf8")

manifest = Path("android/app/src/main/AndroidManifest.xml")
xml = manifest.read_text(encoding="utf8")
xml, label_count = re.subn(r'android:label="[^"]+"',
                           'android:label="CrownFiles: Password Remover"', xml, count=1)
if label_count != 1:
    raise SystemExit("Generated manifest label not found.")
if 'android:allowBackup=' not in xml:
    xml = xml.replace('<application\n', '<application\n        android:allowBackup="false"\n', 1)
manifest.write_text(xml, encoding="utf8")

print("Play package: com.arosoft.crownpasswordstudio")
print("compileSdk: 36; targetSdk: 36; backup: disabled; app label: CrownFiles: Password Remover")
